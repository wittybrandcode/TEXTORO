#!/usr/bin/env node
/**
 * TEXTORO - Zero-Dependency High-Performance CSS Bundler
 * Compiles modular CSS sources from css/src/ into production css/style.css
 * @version 1.1.0
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'css', 'src');
const OUT_FILE = path.join(ROOT, 'css', 'style.css');

// Deterministic build order
const MODULE_ORDER = [
    // 00-tokens
    '00-tokens/variables.css',
    '00-tokens/colors.css',
    '00-tokens/z-index.css',

    // 01-base
    '01-base/reset.css',
    '01-base/scrollbars.css',

    // 02-components
    '02-components/topbar.css',
    '02-components/actionbar.css',
    '02-components/cards.css',
    '02-components/precision-inputs.css',
    '02-components/custom-select.css',
    '02-components/sliders.css',
    '02-components/toggle-chips.css',
    '02-components/modals.css',
    '02-components/tooltips-context.css',

    // 03-panels
    '03-panels/panel-type.css',
    '03-panels/panel-box.css',
    '03-panels/panel-presets.css',
    '03-panels/panel-control.css',
    '03-panels/panel-markers.css',
    '03-panels/panel-motion.css',
    '03-panels/panel-physics.css',
    '03-panels/panel-config.css',

    // 04-utilities
    '04-utilities/grids.css',
    '04-utilities/spacing.css',
    '04-utilities/animations.css'
];

function build() {
    const startTime = Date.now();
    const parts = [];

    parts.push(`/* ==========================================================================\n` +
               `   TEXTORO - Industrial Slate Studio Architecture (Compiled Production Bundle)\n` +
               `   Auto-generated by tools/build-css.js at ${new Date().toISOString()}\n` +
               `   DO NOT EDIT DIRECTLY. Edit source files in css/src/\n` +
               `   ========================================================================== */\n`);

    let totalSourceLines = 0;

    for (const rel of MODULE_ORDER) {
        const fullPath = path.join(SRC_DIR, rel);
        if (!fs.existsSync(fullPath)) {
            console.error(`[BUILD-CSS] ERROR: Source file not found: ${fullPath}`);
            process.exit(1);
        }

        const content = fs.readFileSync(fullPath, 'utf8');
        const lines = content.split('\n').length;
        totalSourceLines += lines;

        parts.push(`\n/* >>> MODULE: ${rel} <<< */\n`);
        parts.push(content);
    }

    const bundle = parts.join('\n');
    fs.writeFileSync(OUT_FILE, bundle, 'utf8');

    const duration = Date.now() - startTime;
    const stats = fs.statSync(OUT_FILE);

    console.log(`[BUILD-CSS] Compiled ${MODULE_ORDER.length} modules (${totalSourceLines} lines) -> ${OUT_FILE}`);
    console.log(`[BUILD-CSS] Output size: ${(stats.size / 1024).toFixed(1)} KB in ${duration}ms`);
}

// Watch mode support
if (process.argv.includes('--watch')) {
    console.log(`[BUILD-CSS] Watching ${SRC_DIR} for changes...`);
    build();
    fs.watch(SRC_DIR, { recursive: true }, (eventType, filename) => {
        if (filename && filename.endsWith('.css')) {
            console.log(`[BUILD-CSS] File changed: ${filename}. Rebuilding...`);
            try { build(); } catch (err) { console.error('[BUILD-CSS] Error:', err.message); }
        }
    });
} else {
    build();
}
